"""Initialize and supervise the executor and OAuth facade as one service."""
import argparse
import http.client
import os
from pathlib import Path
import secrets
import signal
import subprocess
import sys
import time
from .config import Settings, load_env


def initialize(path):
    os.umask(0o077)
    path = Path(path)
    path.parent.mkdir(parents=True,exist_ok=True)
    fd = os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
    values = {
        'CODING_TOOLS_MCP_SERVER_URL':'https://mcp.example.com',
        'CODING_TOOLS_MCP_OAUTH_PASSWORD':secrets.token_urlsafe(32),
        'CODING_TOOLS_MCP_OAUTH_TOKEN_SECRET':secrets.token_hex(32),
        'CODING_TOOLS_MCP_OAUTH_TOKEN_TTL':'3600',
        'SCM_STATE_DIR':'./state','SCM_WORKSPACE':'./workspace',
        'SCM_BACKEND_PORT':'28766','SCM_GATEWAY_PORT':'28767',
        'SCM_PERMISSION_MODE':'safe','SCM_EVENTS_ENABLED':'0',
    }
    with os.fdopen(fd,'w') as f:
        f.write('# Literal KEY=value format; do not add shell quotes.\n')
        f.writelines(f'{k}={v}\n' for k,v in values.items())
    print(f'Created {path}; edit public origin and workspace. Secrets were not printed.')
    return 0


def serve(settings):
    os.umask(0o077)
    settings.workspace.mkdir(parents=True,exist_ok=True)
    settings.state_dir.mkdir(parents=True,exist_ok=True,mode=0o700)
    os.chmod(settings.state_dir,0o700)
    backend_token = secrets.token_urlsafe(48)
    env = dict(os.environ)
    # Do not inherit gateway credentials or runtime-policy overrides into the executor.
    backend_env = {k:v for k,v in env.items() if not k.startswith(('CODING_TOOLS_MCP_','SCM_','MCP_OAUTH_'))}
    backend_env.update(CODING_TOOLS_MCP_AUTH_MODE='bearer',
                       CODING_TOOLS_MCP_AUTH_TOKEN=backend_token,
                       CODING_TOOLS_MCP_TELEMETRY='off')
    command = [sys.executable,'-m','coding_tools_mcp','--workspace',str(settings.workspace),
               '--host','127.0.0.1','--port',str(settings.backend_port),
               '--permission-mode',settings.permission_mode,'--shell-env-inherit','core',
               '--enable-view-image']
    children = []
    stopped = False
    def stop(*_):
        nonlocal stopped
        stopped = True
        for child in children:
            if child.poll() is None:
                child.terminate()
    previous = {s:signal.signal(s,stop) for s in (signal.SIGINT,signal.SIGTERM)}
    try:
        children.append(subprocess.Popen(command,env=backend_env))
        ready = False
        for _ in range(100):
            if stopped or children[0].poll() is not None:
                break
            connection = http.client.HTTPConnection('127.0.0.1',settings.backend_port,timeout=.2)
            try:
                connection.request('POST','/mcp',b'{}',{'Content-Type':'application/json'})
                ready = connection.getresponse().status == 401
            except OSError:
                pass
            finally:
                connection.close()
            if ready:
                break
            time.sleep(.1)
        if stopped:
            return 0
        if not ready:
            raise RuntimeError('Executor did not start with authentication')
        env['SCM_BACKEND_TOKEN'] = backend_token
        children.append(subprocess.Popen([sys.executable,'-m','server_control_mcp','_gateway'],env=env))
        while not stopped:
            if any(child.poll() is not None for child in children):
                return 1
            time.sleep(.2)
        return 0
    finally:
        stop()
        for child in children:
            try:
                child.wait(timeout=8)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait()
        for s,handler in previous.items():
            signal.signal(s,handler)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Self-hosted server control with persistent OAuth')
    parser.add_argument('--env-file',help='Literal environment file generated by init')
    commands = parser.add_subparsers(dest='command',required=True)
    init = commands.add_parser('init',help='Create a private configuration without overwriting')
    init.add_argument('--output',default='.env')
    commands.add_parser('serve',help='Run loopback executor and OAuth gateway')
    commands.add_parser('_gateway',help=argparse.SUPPRESS)
    event = commands.add_parser('emit',help='Append metadata to the local directed event outbox')
    event.add_argument('--recipient',required=True,help='Exact OAuth client_id of the recipient')
    event.add_argument('--kind',required=True)
    args = parser.parse_args(argv)
    try:
        if args.command == 'init':
            return initialize(args.output)
        if args.env_file:
            load_env(args.env_file)
        settings = Settings.load()
        if args.command == 'emit':
            from .events import EventFeed
            print(EventFeed(settings.state_dir/'outbox.sqlite3').emit(args.kind,args.recipient))
            return 0
        if args.command == '_gateway':
            from .gateway import main as gateway_main
            return gateway_main()
        return serve(settings)
    except (ValueError,FileExistsError,RuntimeError) as error:
        print(str(error),file=sys.stderr)
        return 2
